class Forwarder:
    """Where this process's calls for namespaces it does not hold go: the
    holder's endpoint (cached per namespace), found again whenever a call
    fails - and taken over, when its lock or lease is free."""

    def __init__(self, engine, cfg: ForwardConfig, secret: str, own_holder: str):
        self.engine = engine
        self.cfg = cfg
        self.own_holder = own_holder
        self.hostname = socket.gethostname()
        self.client = ForwardClient(cfg, secret, own_holder)
        self._lock = threading.Lock()
        self._routes: dict[str, Endpoint] = {}
        self._written: set[str] = set()   # namespaces written through forwarding since the last flush

    def close(self) -> None:
        self.client.close()

    def routes(self) -> dict[str, str]:
        with self._lock:
            return {ns: f"{ep.host}:{ep.port}" for ns, ep in self._routes.items()}

    def _take(self, ns: str) -> bool:
        """Become `ns`'s writer if its lock or lease is free."""
        try:
            self.engine.namespace(ns)
        except NamespaceBusyError:
            return False
        if self.engine.holds(ns):
            return True
        # (a pinned store that lost its lease is still in the table: drop it
        # and open the namespace again - or find it held)
        self.engine.drop_lost(ns)
        try:
            self.engine.namespace(ns)
        except NamespaceBusyError:
            return False
        return self.engine.holds(ns)

    def _resolve(self, ns: str) -> Endpoint | None:
        if self._take(ns):
            return None
        store = self.engine.store
        reader = getattr(store, "read_owner", None)
        if callable(reader):
            info = reader(ns)
            if info is None or not info.get("fresh"):
                raise _Wait("its lease is changing hands")
            holder = info.get("holder")
        else:
            holder = read_owner_lock(owner_lock_path(store.root, ns))
            if not holder:
                raise _Wait("its new writer is starting")
        ep = parse_holder(holder)
        if ep is None:
            raise ForwardingError(
                f"namespace {ns!r} is held by another process ({holder!r}) that does not accept "
                "forwarded calls (forwarding off, a cluster node, or an older memd). "
                "memd is single-writer per namespace: run one process per root, or turn forwarding "
                "on there")
        if _loopback(ep.host) and ep.hostname != self.hostname:
            raise ForwardingError(
                f"namespace {ns!r} is held by a process on {ep.hostname!r}, whose forwarding "
                "endpoint listens on loopback only: set forward_host / forward_advertise there")
        return ep

    def _route(self, ns: str) -> Endpoint | None:
        with self._lock:
            ep = self._routes.get(ns)
        if ep is not None:
            return ep
        ep = self._resolve(ns)
        if ep is not None:
            with self._lock:
                self._routes[ns] = ep
        return ep

    def _forget(self, ns: str, ep: Endpoint | None) -> None:
        with self._lock:
            if ep is None or self._routes.get(ns) == ep:
                self._routes.pop(ns, None)
        if ep is not None:
            self.client.drop(ep)

    def _alive(self, ns: str, ep: Endpoint):
        """S3: is `ep` still the namespace's (fresh) leaseholder? - checked
        while a call waits for its answer, so a holder frozen past its TTL
        is given up on (it is fenced when it resumes)."""
        reader = getattr(self.engine.store, "read_owner", None)
        if not callable(reader):
            return None

        def alive() -> bool:
            info = reader(ns)
            if info is None or not info.get("fresh"):
                return False
            got = parse_holder(info.get("holder"))
            return got is not None and got.endpoint_id == ep.endpoint_id
        return alive

    def call(self, ns: str, op: str, args: dict, ids: list[str] | None, *, write: bool,
             timeout_s: float | None = None):
        """Run `op` on `ns`'s writer: its result, or LOCAL when this process
        took the namespace (the caller runs it here, with the same `ids`).
        Retries - same request id - until `wait_s` passes without a writer
        answering; ForwardingError then (nothing applied), or
        ForwardTimeoutError if a write's attempt may have been applied."""
        rid = uuid.uuid4().hex
        t0 = time.monotonic()
        deadline = t0 + self.cfg.wait_s
        uncertain = False
        why = ""
        attempt = 0
        while True:
            try:
                ep = self._route(ns)
            except _Wait as w:
                ep, why = False, str(w)
            if ep is None:
                if attempt:
                    METRICS.inc("memd_forward_takeovers_total", ns=ns,
                                help="namespaces this process took over while forwarding to them")
                return LOCAL
            if ep is not False:
                req = {"rid": rid, "op": op, "ns": ns, "args": args, "ids": ids}
                try:
                    reply = self.client.call(ep, req, timeout_s=timeout_s or self.cfg.timeout_s,
                                             alive=self._alive(ns, ep), check_s=self.cfg.check_s)
                except _Unreachable as ex:
                    self._forget(ns, ep)
                    why = str(ex)
                except _Uncertain as ex:
                    self._forget(ns, ep)
                    why = str(ex)
                    uncertain = uncertain or write
                else:
                    if isinstance(reply, _StreamReader):
                        return reply
                    if reply.get("ok"):
                        METRICS.inc("memd_forward_calls_total", op=op, outcome="ok", ns=ns,
                                    help="calls forwarded to the namespace's writer in another process")
                        METRICS.observe("memd_forward_call_ms", (time.monotonic() - t0) * 1000,
                                        help="forwarded call latency, retries included (ms)", op=op)
                        if write:
                            with self._lock:
                                self._written.add(ns)
                        return reply.get("result")
                    err = reply.get("error") or {}
                    if not err.get("retry"):
                        METRICS.inc("memd_forward_calls_total", op=op, outcome="error", ns=ns)
                        _raise_remote(err)
                    why = f"{err.get('code')}: {err.get('message', '')}"
                    if err.get("code") != "overloaded":
                        self._forget(ns, ep)
            METRICS.inc("memd_forward_retries_total", op=op,
                        help="forwarded call attempts that found no writer answering")
            if time.monotonic() >= deadline:
                METRICS.inc("memd_forward_calls_total", op=op, outcome="unavailable", ns=ns)
                if uncertain:
                    raise ForwardTimeoutError(
                        f"namespace {ns!r}: no writer answered within {self.cfg.wait_s:.0f} s ({why}); "
                        "an earlier attempt of this write may have been applied")
                raise ForwardingError(
                    f"namespace {ns!r} is held by another process and no writer answered within "
                    f"{self.cfg.wait_s:.0f} s ({why}); nothing was applied")
            time.sleep(min(0.5, 0.01 * (2 ** min(attempt, 6))) * (0.5 + random.random()))
            attempt += 1

    def probe(self, ns: str) -> bool:
        """At open, for the facade's own namespace held elsewhere: True when
        this process took it after all. Raises when forwarding to its holder
        cannot work (refused credentials, a holder that does not forward);
        one that cannot be reached right now is waited for by the calls."""
        try:
            ep = self._route(ns)
        except _Wait:
            return False
        if ep is None:
            return True
        try:
            reply = self.client.call(ep, {"rid": uuid.uuid4().hex, "op": "ping", "ns": ns,
                                          "args": {}, "ids": None},
                                     timeout_s=min(self.cfg.timeout_s, 10.0))
        except (_Unreachable, _Uncertain):
            self._forget(ns, ep)
            return False
        if isinstance(reply, dict) and not reply.get("ok"):
            self._forget(ns, ep)
        return False

    def take_written(self) -> list[str]:
        with self._lock:
            out, self._written = sorted(self._written), set()
        return out
