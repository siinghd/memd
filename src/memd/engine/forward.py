_log = logging.getLogger(__name__)

PROTOCOL = 1
FORWARDING_MODES = ("auto", "off")
SECRET_FILE = "forward.secret"
# a frame: 4-byte length, a kind byte, the body, and - once the handshake
# keyed the connection - an HMAC-SHA256 of (direction, sequence, kind, body)
_LEN = struct.Struct(">I")
_SEQ = struct.Struct(">Q")
_MAC_LEN = 32
MAX_FRAME = 256 << 20
_MAX_HELLO = 4096          # handshake frames: before authentication, keep them small
_IDLE_S = 600.0            # an idle authenticated connection is closed after this
_DONE_MAX = 8192           # write results remembered for a repeated request id...
_DONE_TTL_S = 900.0        # ...for this long
_STREAM_CHUNK = 256 << 10  # an export streams in chunks of whole lines about this big

# kinds of frame
_HELLO, _REQUEST, _REPLY, _STREAM, _DATA, _END = b"H", b"Q", b"R", b"S", b"D", b"E"

# calls that change the namespace: a repeated request id gets the first
# answer back instead of running again
WRITE_OPS = frozenset({"add", "add_events", "remember", "close_session", "delete", "delete_many",
                       "forget_ids", "destroy_namespace", "compact", "reembed", "audit"})


class ForwardingError(NamespaceBusyError):
    """Another process holds the namespace and the call could not be
    forwarded to it (no writer answered in time, or it does not accept
    forwarded calls). Nothing was applied."""


class ForwardAuthError(ForwardingError):
    """The namespace's holder refused this process's credentials (or could
    not prove its own): the processes do not share the forwarding secret."""


class ForwardTimeoutError(TimeoutError):
    """A forwarded write got no answer and no writer answered its retries in
    time: it may or may not have been applied."""


class ForwardedCallError(RuntimeError):
    """The holder raised an error that has no counterpart here."""


class ForwardNotReady(RuntimeError):
    """(holder side) the Memory is still opening: the caller retries."""


class _Unreachable(Exception):
    """Nothing was sent: the holder cannot be reached (or another process
    answers at its address)."""


class _Uncertain(Exception):
    """The request was sent and no answer came back."""


class _Wait(Exception):
    """Nobody can be reached right now (a lock or lease changing hands)."""


class _AuthFailed(Exception):
    pass


LOCAL = object()   # Forwarder.call: run the call here - this process took the namespace


