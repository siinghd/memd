"""Write forwarding: several processes on one data root.

memd has one writer per namespace: the process holding its lock file (a
local data root) or its lease (s3://) - see NamespaceStore. A second
process opening such a namespace used to get NamespaceBusyError. With
forwarding on (`forwarding="auto"`, the default), its Memory sends that
namespace's writes - and its strongly consistent reads - to the process that
holds it instead, and serves eventual reads from its own read replica:

  - a Memory that may write runs a small endpoint (TCP; 127.0.0.1 and an
    ephemeral port unless `forward_host` / `forward_port` say otherwise) and
    puts its address in what it holds: the lock file's content on a local
    root, the lease holder string on S3
    ("host:pid;fwd=127.0.0.1:41234;id=<endpoint id>");
  - a process that finds a namespace busy reads the holder from there,
    connects and runs the call ON THE HOLDER - the same code a local call
    runs, so quarantine, consolidation, session taint and the audit ledger
    stay the writer's;
  - a connection is authenticated both ways with a secret every process on
    the root can read (`<data dir>/forward.secret`, mode 0600, created on
    first use - or `forward_secret` / MEMD_FORWARD_SECRET), and every frame
    after the handshake carries an HMAC-SHA256 under a key derived for that
    connection (integrity and replay protection; NOT confidentiality);
  - every forwarded call carries a request id, and a call that creates
    records carries their ids, generated by the caller. A retry - after a
    lost reply, a timeout, or a holder that died - is applied at most once:
    a live holder answers a repeated request id from memory (or waits for
    the first attempt still running), and a new holder finds the records in
    the log it replayed when it took the namespace;
  - when the holder goes away its lock frees at once (a lease after its
    TTL), and the next forwarded call takes the namespace: the caller
    becomes its writer and runs the call itself.

A process never applies a write to a namespace it does not hold: the local
path always goes through the namespace's lock or lease, and a holder that
no longer holds it answers "not owner" - nothing applied - to a forwarded
call.
"""
