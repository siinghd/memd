class _StreamReader:
    """The chunks of a streamed answer (an export), as whole lines."""

    def __init__(self, client: "ForwardClient", key, ch: _Channel, meta: dict, timeout_s: float):
        self._client, self._key, self._ch = client, key, ch
        self.meta = meta
        self._timeout_s = timeout_s

    def __iter__(self):
        ch = self._ch
        ok = False
        try:
            ch.sock.settimeout(self._timeout_s)
            while True:
                try:
                    kind, body = ch.recv()
                except (OSError, ConnectionError, _AuthFailed) as ex:
                    raise ForwardingError(f"the holder's stream broke off ({ex})") from ex
                if kind == _DATA:
                    yield from body.splitlines(keepends=True)
                    continue
                trailer = json.loads(body) if kind == _END else {}
                if not trailer.get("ok"):
                    _raise_remote(trailer.get("error") or {"message": "stream ended abnormally"})
                ok = True
                return
        finally:
            if ok:
                self._client._give(self._key, ch)
            else:
                ch.close()


def _raise_remote(err: dict):
    """Raise the holder's error as the same type here, when there is one."""
    from memd.engine import memory as _m
    from memd.storage import crypto, objectstore, replica

    t, msg = str(err.get("type") or ""), str(err.get("message") or "")
    known = {
        "ValueError": ValueError, "TypeError": TypeError, "KeyError": KeyError,
        "PermissionError": PermissionError,
        "ForgetPreviewMismatch": _m.ForgetPreviewMismatch,
        "KeyCustodyError": crypto.KeyCustodyError,
        "KeyUnavailableError": crypto.KeyUnavailableError,
        "ReadOnlyError": objectstore.ReadOnlyError,
        "ReplicaUnavailableError": replica.ReplicaUnavailableError,
        "ForwardTimeoutError": ForwardTimeoutError,
    }
    cls = known.get(t)
    if cls is None:
        raise ForwardedCallError(f"{t or 'error'} in the namespace's writer: {msg}")
    raise cls(msg)


class ForwardClient:
    """Authenticated connections to holders, pooled per endpoint."""

    POOL_IDLE = 16       # idle connections kept per endpoint...
    POOL_IDLE_S = 60.0   # ...for this long (the holder closes them after _IDLE_S)

    def __init__(self, cfg: ForwardConfig, secret: str, client_id: str):
        self.cfg = cfg
        self.secret = secret
        self.client_id = client_id[:128]
        self._lock = threading.Lock()
        self._pool: dict[tuple, list[_Channel]] = {}
        self._closed = False

    def close(self) -> None:
        with self._lock:
            self._closed = True
            pool, self._pool = self._pool, {}
        for chans in pool.values():
            for _t, ch in chans:
                ch.close()

    def drop(self, ep: Endpoint) -> None:
        with self._lock:
            chans = self._pool.pop((ep.host, ep.port, ep.endpoint_id), [])
        for _t, ch in chans:
            ch.close()

    def _give(self, key, ch: _Channel) -> None:
        with self._lock:
            if not self._closed:
                chans = self._pool.setdefault(key, [])
                if len(chans) < self.POOL_IDLE:
                    chans.append((time.monotonic(), ch))
                    return
        ch.close()

    def _take(self, key) -> _Channel | None:
        stale: list[_Channel] = []
        got = None
        with self._lock:
            chans = self._pool.get(key) or []
            while chans:
                t, ch = chans.pop()
                if time.monotonic() - t <= self.POOL_IDLE_S:
                    got = ch
                    break
                stale.append(ch)
        for ch in stale:
            ch.close()
        return got

    def _connect(self, ep: Endpoint) -> _Channel:
        try:
            sock = socket.create_connection((ep.host, ep.port), timeout=self.cfg.connect_timeout_s)
        except OSError as ex:
            raise _Unreachable(f"cannot connect to {ep.host}:{ep.port} ({ex})") from None
        ch = _Channel(sock, b"c")
        try:
            sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
            sock.settimeout(max(5.0, self.cfg.connect_timeout_s * 2))
            kind, body = ch.recv(_MAX_HELLO)
            hello = json.loads(body) if kind == _HELLO else {}
            if hello.get("id") != ep.endpoint_id:
                raise _Unreachable(f"another process answers at {ep.host}:{ep.port} "
                                   "(the namespace's holder is gone)")
            nonce, cnonce = str(hello.get("nonce", "")), secrets.token_hex(16)
            cproof, sproof, key = _keys(self.secret, ep.endpoint_id, nonce, self.client_id, cnonce)
            ch.send(_HELLO, _jdump({"v": PROTOCOL, "client": self.client_id, "cnonce": cnonce,
                                    "proof": cproof}))
            kind, body = ch.recv(_MAX_HELLO)
            ack = json.loads(body) if kind == _HELLO else {}
        except _Unreachable:
            ch.close()
            raise
        except (OSError, ConnectionError, ValueError, _AuthFailed) as ex:
            ch.close()
            raise _Unreachable(f"handshake with {ep.host}:{ep.port} failed ({ex})") from None
        if not ack.get("ok"):
            ch.close()
            raise ForwardAuthError(
                f"the namespace's writer at {ep.host}:{ep.port} refused this process's forwarding "
                "credentials: processes on one data root must share the forwarding secret "
                "(<data dir>/forward.secret, or forward_secret / MEMD_FORWARD_SECRET)")
        if not hmac.compare_digest(str(ack.get("proof", "")), sproof):
            ch.close()
            raise ForwardAuthError(f"the process at {ep.host}:{ep.port} could not prove it holds the "
                                   "forwarding secret; nothing was sent to it")
        ch.key = key
        return ch

    def call(self, ep: Endpoint, req: dict, *, timeout_s: float, alive=None, check_s: float = 0.0):
        """Send one request and wait for its answer: the reply dict, or a
        _StreamReader. _Unreachable: nothing was sent; _Uncertain: sent, no
        answer (within `timeout_s`, or `alive()` said the holder lost the
        namespace meanwhile)."""
        key = (ep.host, ep.port, ep.endpoint_id)
        body = _jdump(req)
        if len(body) > MAX_FRAME:
            raise ValueError(f"a forwarded call is limited to {MAX_FRAME >> 20} MiB")
        ch = self._take(key)
        pooled = ch is not None
        while True:
            if ch is None:
                ch = self._connect(ep)
            try:
                ch.sock.settimeout(max(5.0, timeout_s))
                ch.send(_REQUEST, body)
                break
            except OSError:
                ch.close()
                if not pooled:
                    raise _Uncertain(f"sending to {ep.host}:{ep.port} failed") from None
                ch, pooled = None, False    # a pooled connection the holder closed: once more
        try:
            self._await(ch, timeout_s, alive, check_s)
            ch.sock.settimeout(max(5.0, timeout_s))
            kind, data = ch.recv()
        except _Uncertain:
            ch.close()
            raise
        except (OSError, ConnectionError, ValueError, _AuthFailed) as ex:
            ch.close()
            raise _Uncertain(f"no answer from {ep.host}:{ep.port} ({ex})") from None
        if kind == _STREAM:
            return _StreamReader(self, key, ch, json.loads(data), max(5.0, timeout_s))
        try:
            reply = json.loads(data)
        except ValueError:
            ch.close()
            raise _Uncertain("unreadable answer") from None
        self._give(key, ch)
        return reply

    @staticmethod
    def _await(ch: _Channel, timeout_s: float, alive, check_s: float) -> None:
        deadline = time.monotonic() + timeout_s
        next_check = time.monotonic() + check_s if alive is not None and check_s > 0 else None
        poller = select.poll()
        poller.register(ch.sock, select.POLLIN | select.POLLERR | select.POLLHUP)
        while True:
            left = deadline - time.monotonic()
            if left <= 0:
                raise _Uncertain(f"no answer within {timeout_s:.0f} s")
            if poller.poll(int(min(left, 1.0) * 1000)):
                return
            if next_check is not None and time.monotonic() >= next_check:
                next_check = time.monotonic() + check_s
                try:
                    still = alive()
                except Exception:  # noqa: BLE001 - cannot tell: keep waiting
                    still = True
                if not still:
                    raise _Uncertain("the holder lost the namespace while the call ran")


