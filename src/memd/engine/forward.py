@dataclass
class ForwardConfig:
    mode: str = "auto"
    secret: str | None = None        # forward_secret / MEMD_FORWARD_SECRET
    host: str = "127.0.0.1"          # the endpoint's bind address
    port: int = 0                    # 0: an ephemeral port
    advertise: str | None = None     # host:port other processes connect to (default: bind address)
    wait_s: float = 30.0             # how long a call keeps looking for a writer that answers
    timeout_s: float = 300.0         # how long one attempt waits for the holder's answer
    connect_timeout_s: float = 2.0
    max_inflight: int = 64           # holder: forwarded calls executing at once
    max_conns: int = 256             # holder: connections at once
    queue_wait_s: float = 10.0       # holder: a call waits this long for a slot, then "overloaded"
    check_s: float = 0.0             # S3: how often a call waiting for its answer re-checks the lease

    @property
    def enabled(self) -> bool:
        return self.mode == "auto"

    @classmethod
    def from_config(cls, cfg: dict, forwarding: str | None = None, *,
                    lease_ttl_s: float | None = None) -> "ForwardConfig":
        """From Memory(config=...) keys, else the MEMD_FORWARD* environment.
        `lease_ttl_s` (an s3:// root): a crashed holder's lease frees only
        after it, so a call waits that long plus a margin by default."""
        def pick(key: str, env: str, default):
            v = cfg.get(key)
            if v is None or v == "":
                v = os.environ.get(env)
            return default if v is None or v == "" else v

        mode = str(forwarding or pick("forwarding", "MEMD_FORWARDING", "auto")).strip().lower()
        if mode not in FORWARDING_MODES:
            raise ValueError(f"forwarding must be one of {FORWARDING_MODES}, got {mode!r}")
        wait_default = 30.0 if lease_ttl_s is None else max(30.0, float(lease_ttl_s) + 15.0)
        out = cls(
            mode=mode,
            secret=pick("forward_secret", "MEMD_FORWARD_SECRET", None),
            host=str(pick("forward_host", "MEMD_FORWARD_HOST", "127.0.0.1")),
            port=int(pick("forward_port", "MEMD_FORWARD_PORT", 0)),
            advertise=pick("forward_advertise", "MEMD_FORWARD_ADVERTISE", None),
            wait_s=float(pick("forward_wait_s", "MEMD_FORWARD_WAIT_S", wait_default)),
            timeout_s=float(pick("forward_timeout_s", "MEMD_FORWARD_TIMEOUT_S", 300.0)),
            max_inflight=int(pick("forward_max_inflight", "MEMD_FORWARD_MAX_INFLIGHT", 64)),
            queue_wait_s=float(pick("forward_queue_wait_s", "MEMD_FORWARD_QUEUE_WAIT_S", 10.0)),
            check_s=0.0 if lease_ttl_s is None else max(0.5, float(lease_ttl_s) / 3.0),
        )
        if out.secret is not None and len(out.secret) < 16:
            raise ValueError("forward_secret / MEMD_FORWARD_SECRET must be at least 16 characters")
        return out


def load_secret(cfg: ForwardConfig, data_dir: str) -> str:
    """The forwarding secret: the configured one, else `<data_dir>/
    forward.secret` - created on first use (mode 0600), so every process
    that can read the data directory shares it."""
    if cfg.secret:
        return cfg.secret
    path = os.path.join(data_dir, SECRET_FILE)
    for _ in range(100):
        try:
            with open(path, "rb") as f:
                got = f.read().strip()
        except FileNotFoundError:
            got = None
        if got is not None:
            if len(got) >= 32:
                return got.decode("ascii", errors="replace")
            time.sleep(0.02)      # being written by the process creating it
            continue
        # created whole or not at all: written to a temp file, then linked
        # into place - which fails if another process got there first
        tmp = f"{path}.{os.getpid()}-{secrets.token_hex(4)}.tmp"
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            os.write(fd, secrets.token_hex(32).encode())
            os.fsync(fd)
        finally:
            os.close(fd)
        try:
            os.link(tmp, path)
        except FileExistsError:
            pass
        except OSError:
            # no hard links here: an exclusive create (a reader may see it
            # empty for a moment - the loop above waits for that)
            try:
                os.rename(tmp, path) if not os.path.exists(path) else None
            except OSError:
                pass
        finally:
            try:
                os.unlink(tmp)
            except OSError:
                pass
    raise RuntimeError(f"could not read or create the forwarding secret {path}")


# ---------------------------------------------------------------- holders


@dataclass(frozen=True)
class Endpoint:
    host: str
    port: int
    endpoint_id: str
    hostname: str        # the machine the holder runs on


def holder_string(address: str, endpoint_id: str) -> str:
    """The lock-file content / lease holder of a process that accepts
    forwarded calls (no newline: a lease body is "<holder>\\n<stamp>")."""
    return f"{socket.gethostname()}:{os.getpid()};fwd={address};id={endpoint_id}"


def parse_holder(holder: str | None) -> Endpoint | None:
    """The endpoint a holder string advertises; None when it advertises
    none (forwarding off, a cluster node, an older memd)."""
    if not holder or ";fwd=" not in holder:
        return None
    head, *fields = holder.strip().split(";")
    kv = dict(f.split("=", 1) for f in fields if "=" in f)
    addr, eid = kv.get("fwd"), kv.get("id")
    if not addr or not eid:
        return None
    host, _, port = addr.rpartition(":")
    try:
        return Endpoint(host.strip("[]"), int(port), eid, head.rsplit(":", 1)[0])
    except ValueError:
        return None


def _unspecified(host: str) -> bool:
    """A bind address meaning every interface: not one others can connect to."""
    if not host:
        return True
    try:
        return ipaddress.ip_address(host).is_unspecified
    except ValueError:
        return False


def _loopback(host: str) -> bool:
    if host == "localhost":
        return True
    try:
        return ipaddress.ip_address(host).is_loopback
    except ValueError:
        return False


# ---------------------------------------------------------------- framing


def _shutdown(sock: socket.socket) -> None:
    try:
        sock.shutdown(socket.SHUT_RDWR)
    except OSError:
        pass


def _jdump(obj) -> bytes:
    return json.dumps(obj, separators=(",", ":"), default=_jdefault).encode()


def _jdefault(o):
    name = getattr(o, "name", None)
    if isinstance(name, str) and hasattr(type(o), "__members__"):
        return name                                 # an enum (Source): by name
    if isinstance(o, (set, frozenset, tuple)):
        return list(o)
    item = getattr(o, "item", None)                 # numpy scalars
    if callable(item):
        return item()
    raise TypeError(f"{type(o).__name__} cannot be forwarded")


def _hmac(key: bytes, *parts: bytes) -> bytes:
    return hmac.new(key, b"".join(parts), hashlib.sha256).digest()


class _Channel:
    """Length-prefixed frames over one socket; once keyed (after the
    handshake), every frame carries an HMAC over its direction, its
    sequence number and its bytes - a frame altered, dropped, replayed or
    reflected fails the check and closes the connection."""

    def __init__(self, sock: socket.socket, side: bytes):
        self.sock = sock
        self.key: bytes | None = None
        self.out_tag, self.in_tag = (b"c", b"s") if side == b"c" else (b"s", b"c")
        self.seq_out = self.seq_in = 0

    def send(self, kind: bytes, body: bytes) -> None:
        mac = b""
        if self.key is not None:
            mac = _hmac(self.key, self.out_tag, _SEQ.pack(self.seq_out), kind, body)
            self.seq_out += 1
        head = _LEN.pack(1 + len(body) + len(mac)) + kind
        if len(body) < 65536:
            self.sock.sendall(head + body + mac)
        else:
            self.sock.sendall(head)
            self.sock.sendall(body)
            self.sock.sendall(mac)

    def recv(self, limit: int = MAX_FRAME) -> tuple[bytes, bytes]:
        n = _LEN.unpack(self._exact(_LEN.size))[0]
        extra = 1 + (_MAC_LEN if self.key is not None else 0)
        if n < extra or n > limit + extra:
            raise _AuthFailed(f"bad frame length {n}")
        frame = self._exact(n)
        kind = frame[:1]
        if self.key is None:
            return kind, frame[1:]
        body, mac = frame[1:-_MAC_LEN], frame[-_MAC_LEN:]
        want = _hmac(self.key, self.in_tag, _SEQ.pack(self.seq_in), kind, body)
        if not hmac.compare_digest(mac, want):
            raise _AuthFailed("frame authentication failed")
        self.seq_in += 1
        return kind, body

    def _exact(self, n: int) -> bytes:
        buf = bytearray(n)
        view = memoryview(buf)
        got = 0
        while got < n:
            k = self.sock.recv_into(view[got:], min(n - got, 1 << 20))
            if not k:
                raise ConnectionError("connection closed")
            got += k
        return bytes(buf)

    def close(self) -> None:
        try:
            self.sock.close()
        except OSError:
            pass


def _keys(secret: str, endpoint_id: str, nonce: str, client: str, cnonce: str) -> tuple[str, str, bytes]:
    """(client proof, server proof, connection key) for one handshake - the
    cluster router's request signature (memd.server.cluster._sign) over
    both nonces, so neither side's proof can be replayed to the other.
    (Imported here: a single server never loads the cluster module.)"""
    from memd.server.cluster import _sign

    cproof = _sign(secret, endpoint_id, nonce, client, "forward-client", cnonce)
    sproof = _sign(secret, endpoint_id, nonce, client, "forward-server", cnonce)
    key = bytes.fromhex(_sign(secret, endpoint_id, nonce, client, "forward-key", cnonce))
    return cproof, sproof, key


