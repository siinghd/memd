class _Stream:
    """A handler result sent as a stream (an export): `meta` first, then
    the chunks of `chunks`."""

    def __init__(self, meta: dict, chunks):
        self.meta = meta
        self.chunks = chunks


def _error_payload(ex: BaseException) -> dict:
    from memd.storage.objectstore import LeaseLostError

    if isinstance(ex, (NamespaceBusyError, LeaseLostError, NamespaceClosedError)):
        # this process does not hold the namespace (any more): nothing was
        # applied, the caller finds the writer again
        return {"code": "not_owner", "retry": True, "message": str(ex)[:500]}
    if isinstance(ex, ForwardNotReady):
        return {"code": "not_ready", "retry": True, "message": str(ex)[:500]}
    return {"code": "error", "retry": False, "type": type(ex).__name__, "message": str(ex)[:4000]}


class ForwardServer:
    """The endpoint of a process that may hold namespaces. `handler(op, ns,
    args, ids)` runs one forwarded call (see Memory._serve_forwarded) and
    returns a JSON-able result or a _Stream; NamespaceBusyError /
    LeaseLostError from it mean "not the writer, nothing applied"."""

    def __init__(self, cfg: ForwardConfig, secret: str, handler):
        self.cfg = cfg
        self.secret = secret
        self.handler = handler
        self.endpoint_id = secrets.token_hex(8)
        self._sock = socket.create_server((cfg.host, int(cfg.port)), backlog=128)
        port = self._sock.getsockname()[1]
        if cfg.advertise:
            address = str(cfg.advertise)
        elif _unspecified(cfg.host):
            self._sock.close()
            raise ValueError("forward_host binds every interface: set forward_advertise / "
                             "MEMD_FORWARD_ADVERTISE to the host:port other processes reach this one at")
        else:
            address = f"[{cfg.host}]:{port}" if ":" in cfg.host else f"{cfg.host}:{port}"
        self.address = address
        self.holder = holder_string(address, self.endpoint_id)
        self._lock = threading.Lock()
        self._idle = threading.Condition(self._lock)
        self._conns: set[socket.socket] = set()
        self._inflight = 0
        self._slots = threading.BoundedSemaphore(max(1, int(cfg.max_inflight)))
        # Calls run on these threads, never on a connection's own: a thread
        # that reads an index keeps a SQLite connection of its own until the
        # index closes, so a thread per connection kept two descriptors per
        # connection for good. At most max_inflight, created as needed, reused.
        from concurrent.futures import ThreadPoolExecutor

        self._pool = ThreadPoolExecutor(max_workers=max(1, int(cfg.max_inflight)),
                                        thread_name_prefix="memd-forward-call")
        self._done: "OrderedDict[str, tuple[float, dict]]" = OrderedDict()
        self._running: dict[str, threading.Event] = {}
        self._closing = False
        self._thread: threading.Thread | None = None

    def start(self) -> None:
        self._thread = threading.Thread(target=self._accept_loop, daemon=True, name="memd-forward")
        self._thread.start()

    def stop(self, drain_s: float = 30.0) -> None:
        """Stop serving: new calls are answered "not owner" (the callers
        find the next writer), calls already running finish - within
        `drain_s` - and then every connection is closed."""
        with self._lock:
            if self._closing:
                return
            self._closing = True
        try:
            self._sock.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass
        self._sock.close()
        deadline = time.monotonic() + drain_s
        with self._lock:
            while self._inflight and time.monotonic() < deadline:
                self._idle.wait(max(0.01, deadline - time.monotonic()))
            conns = list(self._conns)
        for c in conns:
            try:
                c.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
        if self._thread is not None and self._thread is not threading.current_thread():
            self._thread.join(timeout=5)
        self._pool.shutdown(wait=False)

    # ------------------------------------------------------------ connections

    def _accept_loop(self) -> None:
        # (a timeout, so the loop also ends where shutting the listening
        # socket down does not wake an accept() blocked on it)
        self._sock.settimeout(1.0)
        while True:
            try:
                conn, _addr = self._sock.accept()
            except socket.timeout:
                if self._closing:
                    return
                continue
            except OSError:
                return                      # closed (stop)
            with self._lock:
                refuse = self._closing or len(self._conns) >= self.cfg.max_conns
                if not refuse:
                    self._conns.add(conn)
            if refuse:
                METRICS.inc("memd_forward_refused_total", reason="connections",
                            help="forwarded connections refused (too many at once, or closing)")
                conn.close()
                continue
            threading.Thread(target=self._serve_conn, args=(conn,), daemon=True,
                             name="memd-forward-conn").start()

    def _serve_conn(self, conn: socket.socket) -> None:
        ch = _Channel(conn, b"s")
        # the whole handshake, however slowly its bytes come, within 5 s
        cut = threading.Timer(max(5.0, self.cfg.connect_timeout_s * 2), _shutdown, args=(conn,))
        cut.daemon = True
        try:
            conn.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
            conn.settimeout(max(5.0, self.cfg.connect_timeout_s * 2))
            cut.start()
            ok = self._handshake(ch)
            cut.cancel()
            if not ok:
                return
            conn.settimeout(_IDLE_S)
            while True:
                kind, body = ch.recv()
                if kind != _REQUEST:
                    return
                self._handle(ch, json.loads(body))
        except _AuthFailed:
            METRICS.inc("memd_forward_auth_failures_total",
                        help="forwarded connections refused: bad credentials or a tampered frame")
        except (OSError, ConnectionError, ValueError):
            pass                            # the caller went away (or sent garbage)
        except Exception:  # noqa: BLE001 - one connection never takes the endpoint down
            _log.exception("memd forward: connection failed")
        finally:
            cut.cancel()
            with self._lock:
                self._conns.discard(conn)
            ch.close()

    def _handshake(self, ch: _Channel) -> bool:
        nonce = secrets.token_hex(16)
        ch.send(_HELLO, _jdump({"v": PROTOCOL, "id": self.endpoint_id, "nonce": nonce}))
        kind, body = ch.recv(_MAX_HELLO)
        msg = json.loads(body) if kind == _HELLO else {}
        client, cnonce, proof = str(msg.get("client", ""))[:128], str(msg.get("cnonce", ""))[:64], \
            str(msg.get("proof", ""))
        cproof, sproof, key = _keys(self.secret, self.endpoint_id, nonce, client, cnonce)
        if len(cnonce) < 16 or not hmac.compare_digest(proof, cproof):
            METRICS.inc("memd_forward_auth_failures_total",
                        help="forwarded connections refused: bad credentials or a tampered frame")
            ch.send(_HELLO, _jdump({"ok": False, "error": "auth"}))
            return False
        ch.send(_HELLO, _jdump({"ok": True, "proof": sproof}))
        ch.key = key
        return True

    # ------------------------------------------------------------ calls

    def _handle(self, ch: _Channel, req: dict) -> None:
        op = str(req.get("op") or "")
        rid = str(req.get("rid") or "")
        if op in WRITE_OPS and rid:
            resp = self._write(req, rid)
        else:
            resp = self._execute(req)
        if isinstance(resp, _Stream):
            self._send_stream(ch, resp)
            return
        try:
            body = _jdump(resp)
        except (TypeError, ValueError) as ex:   # a result that cannot travel
            body = _jdump({"ok": False, "error": _error_payload(ex)})
        ch.send(_REPLY, body)

    def _write(self, req: dict, rid: str) -> dict:
        """A write runs once per request id: a repeat gets the first
        answer, or waits for the first attempt still running."""
        while True:
            with self._lock:
                hit = self._done.get(rid)
                if hit is not None:
                    METRICS.inc("memd_forward_repeats_total",
                                help="forwarded writes answered from an earlier attempt (not run again)")
                    return hit[1]
                ev = self._running.get(rid)
                mine = ev is None
                if mine:
                    ev = self._running[rid] = threading.Event()
            if not mine:
                if not ev.wait(self.cfg.timeout_s):
                    return {"ok": False, "error": {"code": "overloaded", "retry": True,
                                                   "message": "the first attempt is still running"}}
                continue
            resp: dict = {"ok": False, "error": {"code": "error", "retry": False, "type": "RuntimeError",
                                                 "message": "not run"}}
            try:
                resp = self._execute(req)
            finally:
                with self._lock:
                    if resp.get("ok") or not (resp.get("error") or {}).get("retry"):
                        now = time.monotonic()
                        self._done[rid] = (now, resp)
                        while self._done and (len(self._done) > _DONE_MAX
                                              or next(iter(self._done.values()))[0] < now - _DONE_TTL_S):
                            self._done.popitem(last=False)
                    self._running.pop(rid, None)
                ev.set()
            return resp

    def _begin(self) -> dict | None:
        if not self._slots.acquire(timeout=self.cfg.queue_wait_s):
            METRICS.inc("memd_forward_refused_total", reason="overloaded")
            return {"ok": False, "error": {"code": "overloaded", "retry": True,
                                           "message": "too many forwarded calls running"}}
        with self._lock:
            if self._closing:
                self._slots.release()
                return {"ok": False, "error": {"code": "not_owner", "retry": True,
                                               "message": "the holder is closing"}}
            self._inflight += 1
        return None

    def _end(self) -> None:
        with self._lock:
            self._inflight -= 1
            if not self._inflight:
                self._idle.notify_all()
        self._slots.release()

    def _execute(self, req: dict):
        refused = self._begin()
        if refused is not None:
            return refused
        op = str(req.get("op") or "")
        t0 = time.monotonic()
        streaming = False
        try:
            try:
                fut = self._pool.submit(self.handler, op, str(req.get("ns") or ""),
                                        req.get("args") or {}, req.get("ids"))
            except RuntimeError:            # shut down meanwhile: closing
                return {"ok": False, "error": {"code": "not_owner", "retry": True,
                                               "message": "the holder is closing"}}
            out = fut.result()
            if isinstance(out, _Stream):
                streaming = True        # _send_stream ends it
                return out
            METRICS.inc("memd_forward_served_total", op=op, outcome="ok",
                        help="forwarded calls this process ran for another")
            return {"ok": True, "result": out}
        except BaseException as ex:  # noqa: BLE001 - every failure is the caller's answer
            err = _error_payload(ex)
            METRICS.inc("memd_forward_served_total", op=op, outcome=err["code"])
            return {"ok": False, "error": err}
        finally:
            if not streaming:
                self._end()
            METRICS.observe("memd_forward_serve_ms", (time.monotonic() - t0) * 1000,
                            help="forwarded calls run for another process (ms)", op=op)

    def _send_stream(self, ch: _Channel, st: _Stream) -> None:
        try:
            ch.send(_STREAM, _jdump(st.meta))
            buf: list[bytes] = []
            size = 0
            trailer: dict = {"ok": True}
            try:
                for piece in st.chunks:
                    buf.append(piece)
                    size += len(piece)
                    if size >= _STREAM_CHUNK:
                        ch.send(_DATA, b"".join(buf))
                        buf, size = [], 0
                if buf:
                    ch.send(_DATA, b"".join(buf))
            except (OSError, ConnectionError):
                raise
            except BaseException as ex:  # noqa: BLE001 - reported to the caller
                trailer = {"ok": False, "error": _error_payload(ex)}
            ch.send(_END, _jdump(trailer))
        finally:
            close = getattr(st.chunks, "close", None)
            if callable(close):
                close()
            self._end()


